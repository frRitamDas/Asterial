#!/usr/bin/env node
/**
 * Generates gitignored mobile/src/config/runtimeEnv.generated.ts from public
 * environment variables or root .env.local.
 *
 * SECURITY: Only public client variables (NEXT_PUBLIC_SUPABASE_URL,
 * NEXT_PUBLIC_SUPABASE_ANON_KEY, NEXT_PUBLIC_APP_URL) are read.
 * SUPABASE_SERVICE_ROLE_KEY is NEVER read or emitted into mobile bundles.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const dotEnvPath = path.join(rootDir, ".env.local");

function parseDotEnv(filePath) {
  const map = {};
  if (!fs.existsSync(filePath)) return map;
  const lines = fs.readFileSync(filePath, "utf8").split(/\r?\n/);
  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eqIdx = line.indexOf("=");
    if (eqIdx <= 0) continue;
    const key = line.slice(0, eqIdx).trim();
    const val = line
      .slice(eqIdx + 1)
      .trim()
      .replace(/^['"]|['"]$/g, "");
    map[key] = val;
  }
  return map;
}

const localEnv = parseDotEnv(dotEnvPath);

const supabaseUrl =
  process.env.ASTERIAL_SUPABASE_URL ||
  process.env.NEXT_PUBLIC_SUPABASE_URL ||
  localEnv.NEXT_PUBLIC_SUPABASE_URL ||
  "";

const supabaseAnonKey =
  process.env.ASTERIAL_SUPABASE_ANON_KEY ||
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  localEnv.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  "";

const appWebUrl =
  process.env.NEXT_PUBLIC_APP_URL ||
  localEnv.NEXT_PUBLIC_APP_URL ||
  "https://asterial.vercel.app";

const outPath = path.join(
  rootDir,
  "mobile",
  "src",
  "config",
  "runtimeEnv.generated.ts"
);

fs.mkdirSync(path.dirname(outPath), { recursive: true });
const fileContents = `// AUTO-GENERATED BY scripts/prepare-mobile-env.mjs — DO NOT COMMIT
export const GENERATED_MOBILE_ENV = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  appWebUrl: ${JSON.stringify(appWebUrl)},
} as const;
`;

fs.writeFileSync(outPath, fileContents, "utf8");
console.log(
  `Prepared mobile runtime config (Supabase URL configured: ${Boolean(supabaseUrl)})`
);
